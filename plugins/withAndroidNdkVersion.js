const { createRunOncePlugin, withProjectBuildGradle } = require('expo/config-plugins');

const MARKER = '// @generated by withAndroidNdkVersion';
const ANDROID_NDK_OVERRIDE_BLOCK = `${MARKER}
subprojects { subproject ->
  subproject.plugins.withId('com.android.library') {
    subproject.extensions.getByName('android').ndkVersion = rootProject.ext.ndkVersion
  }
}`;

function applyAndroidNdkOverride(contents) {
  if (contents.includes(MARKER)) return contents;
  return `${contents.trimEnd()}\n\n${ANDROID_NDK_OVERRIDE_BLOCK}\n`;
}

function withAndroidNdkVersion(config) {
  return withProjectBuildGradle(config, (config) => {
    if (config.modResults.language !== 'groovy') {
      throw new Error('withAndroidNdkVersion requires a Groovy Android project build file');
    }
    config.modResults.contents = applyAndroidNdkOverride(config.modResults.contents);
    return config;
  });
}

const plugin = createRunOncePlugin(withAndroidNdkVersion, 'blackwave-android-ndk-version', '1.0.0');
plugin.applyAndroidNdkOverride = applyAndroidNdkOverride;

module.exports = plugin;
